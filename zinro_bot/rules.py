def seer_strong_section(role: str | None, ruleset: str = SEER4) -> str:
    """強いほうの指示に入れる、占い入りの節。役職が決まっていれば、その役職の分だけ。"""
    strong = TEXTS[ruleset]["strong"]
    if role in strong:
        return SEER_SECTION_HEAD + "\n" + strong[role] + "\n"
    parts = [SEER_SECTION_HEAD]
    for name in SEER_ROLES:
        parts.append(f"### {name}のとき\n{strong[name]}")
    return "\n".join(parts) + "\n"


def apply_seer(instructions: str, role: str | None, ruleset: str = SEER4) -> str:
    """占いなしを前提にした指示(bot_prompt.md)を、占い入りの場に置き換える。"""
    for old in (PLAIN_FIELD, PLAIN_READING, PLAIN_ROLES_FROM, PLAIN_ROLES_TO):
        if old not in instructions:
            raise ValueError(f"bot_prompt.md に、置き換える箇所がない: {old[:20]}")
    texts = TEXTS[ruleset]
    text = instructions.replace(PLAIN_FIELD, texts["field"]).replace(PLAIN_READING, texts["reading"])
    head = text.index(PLAIN_ROLES_FROM)
    tail = text.index(PLAIN_ROLES_TO)
    return text[:head] + seer_strong_section(role, ruleset) + text[tail:]


def apply_seer_casual(text: str, role: str, ruleset: str = SEER4) -> str:
    """ふつうの相手役の指示(room.CASUAL)を、占い入りの場に置き換える。"""
    for old in (PLAIN_CASUAL_FIELD, PLAIN_CASUAL_READING, PLAIN_CASUAL_ROLES):
        if old not in text:
            raise ValueError(f"CASUAL に、置き換える箇所がない: {old[:20]}")
    texts = TEXTS[ruleset]
    return text.replace(PLAIN_CASUAL_FIELD, texts["casual_field"]).replace(PLAIN_CASUAL_READING, texts["casual_reading"]).replace(PLAIN_CASUAL_ROLES, texts["casual"][role])
