// 結合記号を積み重ねた文字(マヨビーム)。base の後ろに n 個の結合記号を付ける。
function zalgo(base, n) {
  let s = base;
  for (let i = 0; i < n; i++) s += String.fromCodePoint(0x0300 + (i % 0x70));
  return s;
}

// ジャワ文字(U+A9C5)を n 個
function java(n) {
  return String.fromCodePoint(0xa9c5).repeat(n);
}

